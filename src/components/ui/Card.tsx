import React from 'react';
import { cn } from '../../lib/utils';

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  hoverable?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, hoverable = false, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        'rounded-xl border border-zinc-800/80 bg-zinc-900/60 backdrop-blur-md text-zinc-100 shadow-[inset_0_1px_0_0_rgba(255,255,255,0.04)]',
        hoverable && 'transition-colors hover:border-zinc-700/80 hover:bg-zinc-900/80',
        className
      )}
      {...props}
    />
  )
);
Card.displayName = 'Card';

